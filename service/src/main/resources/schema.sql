-- Spring stores configuration only. Patient, sample, result, and delivery data stay out of this database.
CREATE TABLE IF NOT EXISTS machine (
    id BIGINT PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    brand VARCHAR(100),
    sample_type_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS sample_category (
    id BIGINT PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE sample_category ADD COLUMN IF NOT EXISTS sort_order INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS analyzer_result_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machine(id),
    sample_category_id BIGINT NOT NULL REFERENCES sample_category(id),
    result_order INTEGER NOT NULL,
    start_position INTEGER,
    category_length INTEGER,
    factor DECIMAL(18,8) NOT NULL DEFAULT 1,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (machine_id, sample_category_id),
    UNIQUE (machine_id, result_order)
);

CREATE TABLE IF NOT EXISTS dhis2_connection (
    id BIGINT PRIMARY KEY,
    environment VARCHAR(30) NOT NULL UNIQUE,
    base_url VARCHAR(500) NOT NULL,
    username VARCHAR(150) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dhis2_program (
    uid VARCHAR(50) PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES dhis2_connection(id),
    code VARCHAR(100),
    name VARCHAR(200) NOT NULL,
    program_type VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dhis2_program_stage (
    uid VARCHAR(50) PRIMARY KEY,
    program_uid VARCHAR(50) NOT NULL REFERENCES dhis2_program(uid),
    name VARCHAR(200) NOT NULL,
    barcode_data_element_uid VARCHAR(50),
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dhis2_data_element (
    uid VARCHAR(50) PRIMARY KEY,
    code VARCHAR(100),
    name VARCHAR(200) NOT NULL,
    value_type VARCHAR(50) NOT NULL,
    option_set_uid VARCHAR(50),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dhis2_stage_data_element (
    stage_uid VARCHAR(50) NOT NULL REFERENCES dhis2_program_stage(uid),
    data_element_uid VARCHAR(50) NOT NULL REFERENCES dhis2_data_element(uid),
    compulsory BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (stage_uid, data_element_uid)
);

CREATE TABLE IF NOT EXISTS dhis2_program_stage_section (
    uid VARCHAR(50) PRIMARY KEY,
    stage_uid VARCHAR(50) NOT NULL REFERENCES dhis2_program_stage(uid),
    name VARCHAR(200) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS dhis2_section_data_element (
    section_uid VARCHAR(50) NOT NULL REFERENCES dhis2_program_stage_section(uid),
    data_element_uid VARCHAR(50) NOT NULL REFERENCES dhis2_data_element(uid),
    sort_order INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (section_uid, data_element_uid)
);

CREATE TABLE IF NOT EXISTS dhis2_org_unit (
    uid VARCHAR(50) PRIMARY KEY,
    code VARCHAR(100),
    name VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dhis2_org_unit_mapping (
    branch_id BIGINT PRIMARY KEY,
    org_unit_uid VARCHAR(50) NOT NULL REFERENCES dhis2_org_unit(uid)
);

CREATE TABLE IF NOT EXISTS dhis2_result_mapping (
    sample_category_id BIGINT PRIMARY KEY REFERENCES sample_category(id),
    stage_uid VARCHAR(50) NOT NULL,
    data_element_uid VARCHAR(50) NOT NULL,
    source_unit VARCHAR(50),
    target_unit VARCHAR(50),
    multiplier DECIMAL(18,8) NOT NULL DEFAULT 1,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (stage_uid, data_element_uid),
    FOREIGN KEY (stage_uid, data_element_uid) REFERENCES dhis2_stage_data_element(stage_uid, data_element_uid)
);
